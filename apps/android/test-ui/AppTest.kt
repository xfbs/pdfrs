package net.xfbs.specto

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.ParcelFileDescriptor
import android.view.ActionMode
import android.view.Window
import android.view.inspector.WindowInspector
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.test.TouchInjectionScope
import androidx.compose.ui.test.hasContentDescription
import androidx.compose.ui.test.hasText
import androidx.compose.ui.test.junit4.v2.createEmptyComposeRule
import androidx.compose.ui.test.onAllNodesWithText
import androidx.compose.ui.test.onNodeWithContentDescription
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.performTextInput
import androidx.test.core.app.ActivityScenario
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import java.lang.reflect.InvocationTargetException
import java.lang.reflect.Proxy
import org.junit.After
import org.junit.AssumptionViolatedException
import org.junit.Before
import org.junit.Rule
import org.junit.rules.TestRule
import org.junit.runners.model.Statement

/**
 * What the UI tests share: opening a document from the test assets, and waiting for the app to show
 * something.
 *
 * The page itself is drawn on a canvas and invisible to tests, so they look at what surrounds it:
 * the page indicator, the bars, the lists.
 *
 * Run on an emulator with `ANDROID_SERIAL=emulator-5554 ./gradlew connectedDebugAndroidTest` (the
 * serial picks the emulator, and keeps the tests off a phone that happens to be plugged in: the run
 * reinstalls the app). The documents are in `test-ui/assets`, generated by `make-fixtures.py`.
 */
abstract class AppTest {
    @get:Rule
    val compose = createEmptyComposeRule()

    protected val instrumentation = InstrumentationRegistry.getInstrumentation()
    protected var scenario: ActivityScenario<MainActivity>? = null

    /** Which window had the focus instead of the app's when the test ended, if another one had. */
    private var focusElsewhere: String? = null

    /**
     * Says so when a test fails while another window than the app's has the focus: Back, real key
     * presses and the clipboard all go by the focus, and a test that needs one of them fails
     * without it, in a way that says nothing of the cause (a wait that runs out, or Espresso's
     * "waited for the root of the view hierarchy to have window focus").
     *
     * On an emulator in CI it is usually a dialog of the system's.
     */
    @get:Rule
    val focus = TestRule { test, _ ->
        object : Statement() {
            override fun evaluate() {
                try {
                    test.evaluate()
                } catch (skipped: AssumptionViolatedException) {
                    throw skipped
                } catch (failure: Throwable) {
                    val elsewhere = focusElsewhere ?: throw failure
                    throw AssertionError(
                        "The app's window did not have the focus when this test ended " +
                            "($elsewhere). " +
                            "The test failed with: ${failure.message?.lineSequence()?.firstOrNull()}",
                        failure,
                    )
                }
            }
        }
    }

    /** The floating menu beside selected text, while one is showing. */
    @Volatile
    private var floatingMenu: ActionMode? = null

    /** Whether the window is wide enough for the sidebar layout. */
    protected val wide: Boolean
        get() {
            val width = instrumentation.targetContext.resources.configuration.screenWidthDp
            return width >= WIDE_WINDOW_DP
        }

    protected val page get() = compose.onNodeWithTag(PAGE_VIEW_TAG)

    @Before
    fun forgetEverything() {
        // No reading positions, recents, drafts, settings or crashes from earlier tests.
        val target = instrumentation.targetContext
        File(target.filesDir, "documents.json").delete()
        File(target.filesDir, "store").deleteRecursively()
        File(target.filesDir, SpectoApp.CRASH_LOG_FILE).delete()
        target.getSharedPreferences("settings", Context.MODE_PRIVATE).edit().clear().commit()
    }

    /**
     * Keeps the system's own dialogs out of the way.
     *
     * An emulator that is short of breath now and then finds an app "not responding" (its launcher,
     * mostly) and says so in a dialog, which takes the focus from the app under test: Back, keys
     * and the clipboard then go nowhere, and the tests that need them fail. The setting stops such
     * dialogs from being shown, and one that is up already is sent away.
     */
    @Before
    fun noSystemDialogs() {
        shell("settings put global hide_error_dialogs 1")
        shell("am broadcast -a android.intent.action.CLOSE_SYSTEM_DIALOGS")
    }

    /** Runs [command] as the shell user and waits for it to end. */
    protected fun shell(command: String) {
        val output = instrumentation.uiAutomation.executeShellCommand(command)
        ParcelFileDescriptor.AutoCloseInputStream(output).use { it.readBytes() }
    }

    @After
    fun close() {
        // Before the app is closed, which changes it.
        focusElsewhere = if (scenario == null || appHasFocus()) null else focusedWindow()
        scenario?.close()
    }

    /** Whether one of the app's windows (the activity's, a menu's, a dialog's) has the focus. */
    private fun appHasFocus(): Boolean {
        var focused = true
        instrumentation.runOnMainSync {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                focused = WindowInspector.getGlobalWindowViews().any { it.hasWindowFocus() }
            }
        }
        return focused
    }

    /** The window that has the focus, in the system's words. */
    private fun focusedWindow(): String = try {
        val output = instrumentation.uiAutomation.executeShellCommand("dumpsys window displays")
        ParcelFileDescriptor.AutoCloseInputStream(output).bufferedReader().useLines { lines ->
            lines.filter {
                "mCurrentFocus=" in it || "mFocusedApp=" in it
            }.joinToString(", ") { it.trim() }
        }.ifEmpty { "the system did not say which window had it" }
    } catch (e: Exception) {
        "asking the system which window had it failed: $e"
    }

    /**
     * Opens a document from the test assets the way another app would hand it over, and waits for
     * [shows] (usually the page indicator's text).
     */
    protected fun open(asset: String, shows: String) {
        val target = instrumentation.targetContext
        val file = File(target.cacheDir, asset)
        instrumentation.context.assets.open(asset).use { input ->
            file.outputStream().use { input.copyTo(it) }
        }
        launch(asset)
        waitForText(shows)
    }

    /** Leaves the app and opens [asset], which [open] put in place, once more. */
    protected fun reopen(asset: String) = launch(asset)

    private fun launch(asset: String) {
        scenario?.close()
        floatingMenu = null
        val target = instrumentation.targetContext
        scenario = ActivityScenario.launch<MainActivity>(
            Intent(target, MainActivity::class.java)
                .setAction(Intent.ACTION_VIEW)
                .setDataAndType(Uri.fromFile(File(target.cacheDir, asset)), "application/pdf"),
        ).onActivity { activity ->
            // Listens in on what the window is told, to learn of floating menus.
            val window = activity.window
            val told = window.callback
            window.callback = Proxy.newProxyInstance(
                Window.Callback::class.java.classLoader,
                arrayOf(Window.Callback::class.java),
            ) { _, method, arguments ->
                when (method.name) {
                    "onActionModeStarted" -> floatingMenu = arguments[0] as ActionMode
                    "onActionModeFinished" -> if (floatingMenu === arguments[0]) floatingMenu = null
                }
                try {
                    method.invoke(told, *(arguments ?: emptyArray()))
                } catch (e: InvocationTargetException) {
                    throw e.targetException
                }
            } as Window.Callback
        }
    }

    protected fun waitForText(text: String) {
        compose.waitUntil(WAIT_MS) {
            compose.onAllNodesWithText(text).fetchSemanticsNodes().isNotEmpty()
        }
    }

    protected fun waitUntilGone(text: String) {
        compose.waitUntil(WAIT_MS) {
            compose.onAllNodesWithText(text).fetchSemanticsNodes().isEmpty()
        }
    }

    protected companion object {
        /**
         * How long to wait for the app to show something.
         *
         * Generous: an emulator in CI renders in software and can take a while to open a document.
         * A wait that is satisfied sooner costs nothing.
         */
        const val WAIT_MS = 30_000L
    }

    /**
     * The point of the current page that is ([x], [fromTop]) points from its top-left corner.
     *
     * The test documents' pages are A4 and shown fitted and centered.
     */
    protected fun TouchInjectionScope.pagePoint(x: Float, fromTop: Float): Offset {
        val margin = 8 * density
        val zoom = minOf((width - 2 * margin) / 595f, (height - 2 * margin) / 842f)
        val left = (width - 595f * zoom) / 2
        val top = (height - 842f * zoom) / 2
        return Offset(left + x * zoom, top + fromTop * zoom)
    }

    /** Picks an item of the overflow menu. */
    protected fun menu(item: String) {
        compose.onNodeWithContentDescription("More").performClick()
        compose.onNodeWithText(item).performClick()
        compose.waitForIdle()
    }

    /**
     * Picks an item of the floating menu beside selected text.
     *
     * That menu is a window of the system's, outside Compose and out of a test's reach, so the item
     * is chosen in the menu behind it, which the activity's window is told about (see [launch]).
     */
    protected fun textMenu(item: String) {
        compose.waitUntil(WAIT_MS) {
            var chosen = false
            instrumentation.runOnMainSync {
                val menu = floatingMenu?.menu ?: return@runOnMainSync
                val entry = (0 until menu.size()).map(menu::getItem).firstOrNull {
                    it.title.toString() == item
                }
                checkNotNull(entry) { "the text menu has no \"$item\"" }
                chosen = menu.performIdentifierAction(entry.itemId, 0)
            }
            chosen
        }
    }

    /**
     * Picks an item of the view menu (layout and fit), behind the button left of the overflow menu.
     */
    protected fun view(item: String) {
        compose.onNodeWithTag(VIEW_BUTTON_TAG).performClick()
        compose.onNodeWithText(item).performClick()
        compose.waitForIdle()
    }

    /** The item of an open view menu called [item], if it is the one ticked. */
    protected fun chosen(item: String) =
        compose.onNode(hasText(item) and hasContentDescription("Chosen"))

    /** "Go to page" with [text] typed into its field, whose label names the [range]. */
    protected fun goTo(text: String, range: String) {
        menu("Go to page")
        compose.onNodeWithText("Page ($range)").performTextInput(text)
        compose.onNodeWithText("Go").performClick()
    }
}
